import os
import shutil

# --- 1. НАСТРОЙКА ПУТЕЙ И ПАПОК ---
# Прописываем путь сразу внутрь папки "УЗИ", где лежат подпапки с пациентами
source_folder = "D:/ВСЕ УЗИ БАЛТЗДРАВА/УЗИ"

# Указываем, что папка результатов должна быть рядом, в корне "ВСЕ УЗИ БАЛТЭЗДРАВА"
target_folder = "D:/ВСЕ УЗИ БАЛТЗДРАВА/Брюшная_полость"

# Расширяем список ключевых слов (срезали окончания, чтобы ловить "печень", "печени" и т.д.)
keywords = ["живот", "БП","брюшн","Брюшная_полость","брюшная_полость", "ОБП","abdomen", "abdominal", "печен", "селезен", "поджелуд", "обп", "obp", "желчн"]

# --- 2. ПОДГОТОВКА И ПРОВЕРКА ДИРЕКТОРИЙ ---
# Если папки "Брюшная_полость" еще нет на диске D, создаем её автоматически
if not os.path.exists(target_folder):
    os.makedirs(target_folder)

# Создаем счетчик для подходящих файлов (УЗИ брюшной полости)
moved_count = 0

# Создаем счетчик абсолютно всех файлов, которые робот встретит на своем пути
total_seen_files = 0

print("--- НАЧАЛО ДИАГНОСТИКИ И ПОИСКА ---")

# --- 3. ГЛАВНЫЙ ЦИКЛ ОБХОДА И ДИАГНОСТИКИ ---
# Проверяем, существует ли сама папка "УЗИ". Если адрес ошибочный, Python предупредит нас
if not os.path.exists(source_folder):
    print(f"ОШИБКА: Путь {source_folder} не найден! Проверьте имя папки.")
else:
    # Запускаем автоматический обход всех папок пациентов внутри папки "УЗИ"
    for root, dirs, files in os.walk(source_folder):
       
        # Перебираем файлы текущего пациента по одному
        for file in files:
            # Увеличиваем общий счетчик встреченных файлов на +1
            total_seen_files += 1
           
            # Переводим имя файла в нижний регистр для точного сравнения букв
            file_lower = file.lower()
           
            # ДИАГНОСТИКА: Выводим в терминал имена первых 5 файлов, чтобы понять, как они подписаны
            if total_seen_files <= 5:
                print(f"Робот видит файл пациента: {file}")
           
            # Сбрасываем флаг поиска перед проверкой ключевых слов
            is_target_file = False
           
            # Проверяем, есть ли хоть одно ключевое слово в названии текущего файла
            for word in keywords:
                if word in file_lower:
                    is_target_file = True
                    break # Слово нашлось, прекращаем проверку остальных слов для этого файла
           
            # --- 4. БЕЗОПАСНОЕ КОПИРОВАНИЕ ---
            # Если файл содержит нужное слово (например, "обп" или "печен"):
            if is_target_file:
                # Строим полный путь к файлу там, где он лежит сейчас (у пациента)
                old_file_path = os.path.join(root, file)
               
                # Извлекаем фамилию пациента (имя папки, в которой лежит файл)
                parent_folder_name = os.path.basename(root)
               
                # Создаем новое уникальное имя: Фамилия_ИмяФайла.doc
                new_file_name = f"{parent_folder_name}_{file}"
               
                # Строим новый полный путь внутри папки "Брюшная_полость"
                new_file_path = os.path.join(target_folder, new_file_name)
               
                # Копируем файл. Если он занят или заблокирован, программа не вылетит
                try:
                    shutil.copy2(old_file_path, new_file_path)
                    print(f"Успешно скопирован: {new_file_name}")
                    moved_count += 1 # Прибавляем единицу к счетчику успешных переносов
                except Exception as e:
                    print(f"Ошибка копирования {file}: {e}")

# --- 5. ФИНАЛЬНЫЙ ОТЧЕТ В ТЕРМИНАЛЕ ---
print("----------------------------------------")
print(f"Всего файлов проверено у пациентов: {total_seen_files}")
print(f"Всего файлов скопировано в 'Брюшная_полость': {moved_count}")