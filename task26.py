# 1. Задаем фиксированный курс валют
# Курс доллара к рублю (например, 1 доллар = 90 рублей)
USD_TO_RUB = 90.0

print("--- Простой конвертер валют ---")
print("1. Доллары в Рубли")
print("2. Рубли в Доллары")

# 2. Получаем выбор пользователя
choice = input("Выберите направление конвертации (1 или 2): ")

# 3. Логика конвертации
if choice == "1":
    # Конвертируем USD в RUB
    usd_amount = float(input("Введите сумму в долларах ($): "))
    rub_result = usd_amount * USD_TO_RUB
    # Округляем результат до 2 знаков после запятой
    print(f"Результат: ${usd_amount} = {round(rub_result, 2)} руб.")

elif choice == "2":
    # Конвертируем RUB в USD
    rub_amount = float(input("Введите сумму в рублях (руб.): "))
    usd_result = rub_amount / USD_TO_RUB
    # Округляем результат до 2 знаков после запятой
    print(f"Результат: {rub_amount} руб. = ${round(usd_result, 2)}")

else:
    # Если пользователь ввел что-то другое
    print("Ошибка: неверный выбор. Пожалуйста, запустите программу снова и выберите 1 или 2.")

